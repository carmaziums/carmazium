import type { MetadataRoute } from "next"
import { serverBackendFetch } from "@/lib/serverBackendFetch"

// Keep the established, working sitemap URL and the site's www canonical host.
const BASE_URL = "https://www.carmazium.com"

// The public listing/blog APIs are paginated. A single ?limit=1000 request
// silently omitted newer inventory and guides as the marketplace grew.
// Reserve headroom below Google's 50,000-URL sitemap limit for static routes.
// Large inventories beyond these ceilings require separate indexed sitemaps.
const PAGE_SIZE = 250
const MAX_LISTING_URLS = 35_000
const MAX_BLOG_URLS = 12_000

export const revalidate = 3600

const STATIC_ROUTES = [
    "",
    "/search",
    "/used-car-types",
    "/sell",
    "/pricing",
    "/pricing/traders",
    "/about",
    "/download-app",
    "/contact",
    "/services",
    "/services/delivery",
    "/services/inspection",
    "/services/finance",
    "/services/warranty",
    "/how-it-works",
    "/reviews",
    "/auctions",
    "/auctions/how-it-works",
    "/compare",
] as const

interface SitemapRecord {
    slug: string
    updatedAt?: string | null
    status?: string | null
    type?: string | null
    noIndex?: boolean | null
}

interface PagedResponse {
    data?: unknown
    pagination?: { totalPages?: number | null }
}

function isLikelyTestListingSlug(slug: string): boolean {
    // Match the rule in /buy-cars/[slug]'s metadata; do not expose obvious tests.
    return /(^|-)(undefined|test\d*|aaa|qqq|www)(-|$)/i.test(slug)
}

function validSlug(row: unknown): row is SitemapRecord {
    if (!row || typeof row !== "object") return false
    const slug = (row as Partial<SitemapRecord>).slug
    // Slugs are generated by the backend as lowercase hyphenated URL segments.
    // Reject malformed or injected paths rather than placing them in sitemap URLs.
    return typeof slug === "string" && /^[a-z0-9][a-z0-9-]{0,190}$/i.test(slug)
}

function safeLastModified(value: string | null | undefined): Date | undefined {
    if (typeof value !== "string") return undefined
    const date = new Date(value)
    return Number.isFinite(date.getTime()) ? date : undefined
}

/**
 * Fetch canonical public URLs from every available page, not just page 1.
 * The public retail feed now returns ACTIVE listings only. Direct links to
 * SOLD/OFFER_ACCEPTED vehicles remain valid but are not indexable.
 * The blog feed returns published articles, including records intentionally
 * flagged noIndex. Respect the editorial noIndex decision in this sitemap.
 *
 * Never query the authenticated trade auction feed or mutate customer records.
 * On a transient upstream error, keep the static routes and pages successfully
 * retrieved, and log which segment needs retrying during the next revalidation.
 */
async function fetchSitemapRecords(kind: "listings" | "blog", maxRecords: number): Promise<SitemapRecord[]> {
    const records: SitemapRecord[] = []
    const seen = new Set<string>()
    const pageCap = Math.ceil(maxRecords / PAGE_SIZE)

    for (let page = 1; page <= pageCap; page++) {
        const query = new URLSearchParams({
            page: String(page),
            limit: String(PAGE_SIZE),
            ...(kind === "listings" ? { sortBy: "newest" } : {}),
        })

        let response: Response
        try {
            response = await serverBackendFetch(
                "/" + kind + "?" + query.toString(),
                { next: { revalidate: 3600 } },
                { timeoutMs: 8_000, retries: 1 },
            )
            if (!response.ok) {
                console.warn("[sitemap] upstream request failed", kind, page, response.status)
                break
            }

            const payload = (await response.json()) as PagedResponse
            if (!Array.isArray(payload.data)) {
                console.warn("[sitemap] unexpected pagination payload", kind, page)
                break
            }

            const rows: unknown[] = payload.data
            for (const row of rows) {
                if (!validSlug(row) || seen.has(row.slug)) continue
                if (kind === "listings") {
                    if (isLikelyTestListingSlug(row.slug)) continue
                    if (row.type !== "CLASSIFIED" || row.status !== "ACTIVE") continue
                } else if (row.status !== "PUBLISHED" || row.noIndex === true) {
                    // Match the individual blog page's robots metadata: a
                    // published-but-noindex article must not be in sitemap.xml.
                    continue
                }

                seen.add(row.slug)
                // Retain only sitemap fields: full listing rows contain large
                // photo arrays and seller data that must not accumulate in memory.
                records.push({ slug: row.slug, updatedAt: row.updatedAt })
                if (records.length >= maxRecords) break
            }

            if (records.length >= maxRecords) {
                console.warn("[sitemap] URL budget reached; split sitemap before further growth", kind, maxRecords)
                break
            }
            const totalPages = payload.pagination?.totalPages
            if (typeof totalPages === "number" && Number.isFinite(totalPages) && page >= totalPages) break
            if (rows.length < PAGE_SIZE) break
            if (page === pageCap) {
                console.warn("[sitemap] page budget exhausted; add sitemap sharding", kind, pageCap)
            }
        } catch {
            console.warn("[sitemap] upstream unavailable; will retry at revalidation", kind, page)
            break
        }
    }

    return records
}

export default async function sitemap(): Promise<MetadataRoute.Sitemap> {
    const staticEntries = STATIC_ROUTES.map((route) => ({
        url: BASE_URL + route,
        changeFrequency: route === "" ? ("daily" as const) : ("weekly" as const),
        priority: route === "" ? 1.0 : route === "/search" || route === "/sell" ? 0.9 : 0.7,
    }))

    const [listings, blogPosts] = await Promise.all([
        fetchSitemapRecords("listings", MAX_LISTING_URLS),
        fetchSitemapRecords("blog", MAX_BLOG_URLS),
    ])

    const listingEntries = listings.map((listing) => ({
        url: BASE_URL + "/buy-cars/" + listing.slug,
        ...(safeLastModified(listing.updatedAt) ? { lastModified: safeLastModified(listing.updatedAt) } : {}),
        changeFrequency: "weekly" as const,
        priority: 0.8,
    }))

    const blogEntries = blogPosts.map((post) => ({
        url: BASE_URL + "/blog/" + post.slug,
        ...(safeLastModified(post.updatedAt) ? { lastModified: safeLastModified(post.updatedAt) } : {}),
        changeFrequency: "monthly" as const,
        priority: 0.6,
    }))

    return [
        ...staticEntries,
        { url: BASE_URL + "/blog", changeFrequency: "weekly" as const, priority: 0.7 },
        ...listingEntries,
        ...blogEntries,
    ]
}

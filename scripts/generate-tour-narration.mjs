import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import ts from 'typescript';

const source = readFileSync(new URL('../src/lib/guidedWebsiteTour.ts', import.meta.url), 'utf8');
const exports = {};
new Function('exports', ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText)(exports);
const scripts = {};
for (const role of ['BUYER', 'SELLER', 'DEALER', 'CONTRACTOR', 'FINANCE_PARTNER', 'INSURANCE_PARTNER']) {
    for (const dealerProfile of [undefined, {}]) {
        for (const step of exports.getGuidedWebsiteSteps({ id: 'catalog', role, dealerProfile })) {
            const text = `${step.title}. ${step.description}`;
            const key = createHash('sha256').update(text).digest('hex');
            scripts[key] = text;
        }
    }
}
const output = '// Generated by scripts/generate-tour-narration.mjs. Public tour copy only.\n'
    + 'export const TOUR_NARRATION: Readonly<Record<string, string>> = Object.freeze('
    + JSON.stringify(Object.fromEntries(Object.entries(scripts).sort()), null, 2) + ');\n';
const destination = new URL('../backend/src/ai/tour-narration.catalog.ts', import.meta.url);
if (process.argv.includes('--check')) {
    if (readFileSync(destination, 'utf8') !== output) throw new Error('Tour narration is out of date. Run node scripts/generate-tour-narration.mjs');
} else writeFileSync(destination, output);
console.log(`Tour narration catalog: ${Object.keys(scripts).length} approved scripts`);

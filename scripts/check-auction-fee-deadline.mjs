// Read-only regression contract for one authoritative deadline on all clients.
import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
const read = path => readFileSync(path, 'utf8')
const service = read('backend/src/auctions/auctions.service.ts')
const helper = read('backend/src/auctions/buyer-fee-deadline.ts')
const cron = read('backend/src/tasks/unpaid-auction-fee-expiry.service.ts')
const web = read('src/app/auctions/live/[id]/page.tsx')
const won = read('src/app/dashboard/dealer/auctions/won/page.tsx')
const mobile = read('carmazium app/carmazium app/src/screens/vehicle/AuctionDetailScreen.tsx')
const complete = read('carmazium app/carmazium app/src/screens/main/AuctionCompleteScreen.tsx')
const bids = read('carmazium app/carmazium app/src/screens/buyer/BuyerBidsScreen.tsx')
assert.match(helper, /won \+ BUYER_FEE_GRACE_MS/, 'backend deadline must derive from wonAt')
assert.match(service, /buyerFeeDeadlineAt: buyerFeeDeadlineAt\(auction\)/, 'API must serialize exact deadline')
assert.match(web, /BuyerFeeCountdown deadline=\{auction\.buyerFeeDeadlineAt\}/)
assert.match(won, /BuyerFeeCountdown deadline=\{auction\.buyerFeeDeadlineAt\}/)
assert.match(mobile, /formatBuyerFeeRemaining\(auction\?\.buyerFeeDeadlineAt, nowMs\)/)
assert.match(complete, /getAuction\(auctionId\)/, 'winner screen revalidates after navigation')
assert.match(complete, /fresh\.buyerFeeDeadlineAt/)
assert.match(bids, /auction\?\.buyerFeeDeadlineAt \?\? null/)
assert.doesNotMatch(mobile, /Date\.now\(\) \+ AUCTION_PAYMENT_GRACE_MS/, 'no socket-time deadline')
assert.match(cron, /buyerFeeReminder24SentAt/)
assert.match(cron, /buyerFeeReminder6SentAt/)
assert.match(cron, /@Cron\('0 \* \* \* \*'\)/, 'existing expiry cadence unchanged')
console.log('Buyer-fee deadline client and scheduler contract passed.')

import { readFileSync, writeFileSync } from 'node:fs';

// The website owns the task order, copy and eligibility rules. Native keeps
// generated local modules so Metro never needs to bundle the Next application.
const root = new URL('../', import.meta.url);
for (const name of ['dealerAttention', 'userAttention']) {
  const source = readFileSync(new URL(`src/lib/${name}.ts`, root), 'utf8');
  const output = '// Generated by scripts/sync-dashboard-attention.mjs. Edit the website source.\n'
    + source.replaceAll('"@/lib/', '"./');
  const target = new URL(`carmazium app/carmazium app/src/lib/${name}.ts`, root);
  if (process.argv.includes('--check')) {
    if (readFileSync(target, 'utf8') !== output) throw Error(`Dashboard attention rules drifted: ${name}`);
  } else writeFileSync(target, output);
}
console.log('Website and native dashboard attention rules match.');
